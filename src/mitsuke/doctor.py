"""`mitsuke doctor`: is this machine ready, and does the model produce the vectors it should?

Each check is {"name", "status": ok|warn|fail, "detail", "fix"?}. The embed check compares a synthetic test image
and a test phrase against reference vectors recorded with MLX bf16 (`doctor_ref.npz`, generated by
`python -m mitsuke.doctor --record`).
"""

from __future__ import annotations

import importlib
import os
import platform
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

from . import paths
from .model import DEFAULT_MODEL, is_cached, model_id

REF_PATH = Path(__file__).with_name("doctor_ref.npz")
REF_TEXT = "a red circle and a blue square on a yellow background"
MIN_FREE_GB = 2


def probe_image() -> Image.Image:
    """Deterministic 256×256 test card drawn with numpy only (no font / anti-aliasing differences)."""
    y, x = np.mgrid[0:256, 0:256]
    a = np.zeros((256, 256, 3), np.uint8)
    a[...] = (235, 205, 40)
    a[(x - 80) ** 2 + (y - 90) ** 2 < 50**2] = (210, 30, 30)
    a[(x > 140) & (x < 220) & (y > 130) & (y < 210)] = (30, 60, 200)
    return Image.fromarray(a)


def _check(name, status, detail, fix=None):
    d = {"name": name, "status": status, "detail": detail}
    if fix:
        d["fix"] = fix
    return d


def check_platform():
    mac = sys.platform == "darwin"
    arm = platform.machine() == "arm64"
    detail = f"{platform.system()} {platform.mac_ver()[0] or platform.release()} {platform.machine()}"
    if mac and arm:
        return _check("platform", "ok", detail)
    return _check("platform", "warn", detail, "MLX needs a Mac with Apple Silicon; other systems are not supported yet")


def check_memory():
    try:
        mem = int(subprocess.run(["sysctl", "-n", "hw.memsize"], capture_output=True, text=True, timeout=5).stdout)
    except (OSError, ValueError, subprocess.SubprocessError):
        return _check("memory", "warn", "unknown")
    gb = mem / 2**30
    return _check("memory", "ok" if gb >= 16 else "warn", f"{gb:.0f} GB", None if gb >= 16 else "8 GB works but indexing is slow")


def check_python():
    v = sys.version_info
    ok = v >= (3, 12)
    return _check("python", "ok" if ok else "fail", f"{v.major}.{v.minor}.{v.micro} ({sys.executable})", None if ok else "Python 3.12+ required")


def check_uv():
    p = shutil.which("uv")
    return _check("uv", "ok" if p else "warn", p or "not found", None if p else "install uv: https://docs.astral.sh/uv/")


def check_imports():
    out = []
    for mod, required, why in [
        ("mlx.core", True, "inference"), ("mlx_vlm", True, "EmbeddingGemma 2 on MLX"), ("PIL", True, "decoding"),
        ("pillow_heif", False, "HEIC / HEIF"), ("psd_tools", False, "PSB and 16/32-bit PSD"), ("rawpy", False, "camera RAW"),
        ("watchdog", False, "index --watch (falls back to polling)"), ("cv2", False, "video and EXR / HDR"),
    ]:
        try:
            m = importlib.import_module(mod)
            ver = getattr(m, "__version__", "") or getattr(sys.modules.get(mod.split(".")[0]), "__version__", "")
            out.append(_check(f"import {mod}", "ok", str(ver) or "ok"))
        except Exception as e:  # noqa: BLE001
            out.append(_check(f"import {mod}", "fail" if required else "warn", f"{type(e).__name__}: {e}", f"needed for {why}: run `uv sync`"))
    return out


def check_dir(name, d: Path):
    try:
        d.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=d, prefix=".probe"):
            pass
    except OSError as e:
        return _check(name, "fail", f"{d}: {e}", "check permissions or set MITSUKE_HOME / MITSUKE_CACHE")
    free = shutil.disk_usage(d).free / 2**30
    if free < MIN_FREE_GB:
        return _check(name, "warn", f"{d} (only {free:.1f} GB free)", "free some disk space")
    return _check(name, "ok", f"{d} ({free:.0f} GB free)")


def check_index():
    try:
        from .store import Store

        s = Store()
        n = s.db.execute("SELECT COUNT(*) FROM files").fetchone()[0]
        roots = s.roots()
        offline = [r["path"] for r in roots if not os.path.isdir(r["path"])]
        s.close()
    except Exception as e:  # noqa: BLE001
        return _check("index", "fail", f"{type(e).__name__}: {e}", "the index file may be damaged; move it away and re-run `mitsuke index`")
    if offline:
        return _check("index", "warn", f"{n} files, {len(roots)} folders; offline: {', '.join(offline)}", "connect the drive, or `mitsuke remove <folder>`")
    return _check("index", "ok", f"{n} files in {len(roots)} folders")


def check_decode():
    """Write tiny files in each format we can produce here, decode them back."""
    from .decode import load_preview

    base = probe_image()
    results, failed = [], []
    with tempfile.TemporaryDirectory() as td:
        samples = {}
        for ext, kw in [("jpg", {}), ("png", {}), ("webp", {}), ("gif", {}), ("bmp", {}), ("tiff", {})]:
            p = Path(td, f"probe.{ext}")
            base.save(p, **kw)
            samples[ext] = p
        p16 = Path(td, "probe16.tiff")
        Image.fromarray((np.asarray(base.convert("L"), np.uint16) * 257)).save(p16)
        samples["tiff16"] = p16
        try:
            import pillow_heif  # noqa: F401

            p = Path(td, "probe.heic")
            base.save(p, format="HEIF")
            samples["heic"] = p
        except Exception:  # noqa: BLE001
            failed.append("heic (pillow-heif missing)")
        try:
            from psd_tools import PSDImage

            p = Path(td, "probe.psd")
            PSDImage.frompil(base).save(p)
            samples["psd"] = p
        except Exception:  # noqa: BLE001
            failed.append("psd (psd-tools missing)")
        for name, p in samples.items():
            try:
                pv = load_preview(p, 256)
                px = np.asarray(pv.image.convert("RGB"), np.float32)
                ref = np.asarray(base.convert("RGB") if name != "tiff16" else base.convert("L").convert("RGB"), np.float32)
                err = float(np.abs(px - ref).mean()) if px.shape == ref.shape else 999.0
                (results if err < 12 else failed).append(name if err < 12 else f"{name} (pixels off by {err:.0f})")
            except Exception as e:  # noqa: BLE001
                failed.append(f"{name} ({type(e).__name__}: {e})")
    try:
        import rawpy

        results.append(f"raw (LibRaw {rawpy.libraw_version})")
    except Exception:  # noqa: BLE001
        failed.append("raw (rawpy missing)")
    status = "ok" if not failed else "warn"
    return _check("decode", status, "ok: " + ", ".join(results) + (("; failed: " + ", ".join(failed)) if failed else ""),
                  None if not failed else "run `uv sync` to install the optional decoders")


def check_model(download: bool):
    repo = model_id()
    if repo == "fake":
        return _check("model", "ok", "fake embedder (MITSUKE_EMBEDDER=fake)")
    if not is_cached(repo) and download:
        try:
            from huggingface_hub import snapshot_download

            snapshot_download(repo)
        except Exception as e:  # noqa: BLE001
            return _check("model", "fail", f"download failed: {type(e).__name__}: {e}", "check the network and retry `mitsuke doctor --download`")
    if is_cached(repo):
        return _check("model", "ok", f"{repo} (cached)")
    return _check("model", "warn", f"{repo} not downloaded yet (~1.5 GB; also happens on first `mitsuke index`)", "mitsuke doctor --download")


def check_embed():
    repo = model_id()
    if repo != "fake" and not is_cached(repo):
        return _check("embed", "warn", "skipped (model not downloaded)", "mitsuke doctor --download")
    try:
        from .model import get_embedder

        e = get_embedder()
        iv = e.embed_images([probe_image()], tokens=140)[0]
        tv = e.embed_texts([REF_TEXT])[0]
    except Exception as ex:  # noqa: BLE001
        return _check("embed", "fail", f"{type(ex).__name__}: {ex}", "run `uv sync`; on non-Apple machines MLX is unavailable")
    if not (np.isfinite(iv).all() and np.isfinite(tv).all()):
        return _check("embed", "fail", "model returned NaN", "never run EmbeddingGemma 2 in float16; use the bf16 MLX weights")
    if repo != DEFAULT_MODEL or not REF_PATH.exists():
        return _check("embed", "ok", f"image·text cosine {float(iv @ tv):.3f} (no reference for {repo})")
    ref = np.load(REF_PATH)
    ci, ct = float(iv @ ref["image"].astype(np.float32)), float(tv @ ref["text"].astype(np.float32))
    ok = ci > 0.99 and ct > 0.99
    return _check("embed", "ok" if ok else "fail", f"matches reference (image {ci:.4f}, text {ct:.4f})" if ok else
                  f"differs from reference (image {ci:.4f}, text {ct:.4f})", None if ok else "re-download the model: `mitsuke doctor --download` after clearing the HF cache")


def run(download: bool = False, embed: bool = True) -> list[dict]:
    checks = [check_platform(), check_memory(), check_python(), check_uv(), *check_imports(),
              check_dir("index folder", paths.home_dir()), check_dir("cache folder", paths.cache_dir()),
              check_index(), check_decode(), check_model(download)]
    if embed:
        checks.append(check_embed())
    return checks


def _record():
    from .model import MLXEmbedder

    e = MLXEmbedder(DEFAULT_MODEL)
    np.savez(REF_PATH, image=e.embed_images([probe_image()], tokens=140)[0].astype(np.float16),
             text=e.embed_texts([REF_TEXT])[0].astype(np.float16))
    print("wrote", REF_PATH)


if __name__ == "__main__":
    if "--record" in sys.argv:
        _record()
